/** "12 March 2026" in another language; anything else is left as written. */
const localDate = (date: string, write: (day: string, month: number, year: string) => string) =>
  date.replace(/^(\d{1,2}) ([A-Za-z]+) (\d{4})$/, (whole, day: string, month: string, year: string) => {
    const index = monthIndex.indexOf(month.toLowerCase());
    return index < 0 ? whole : write(day, index, year);
  });

